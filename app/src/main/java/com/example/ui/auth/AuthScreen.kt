private const val TAG = "PrismAuth"

@Composable
fun AuthScreen(
    onAuthSuccess: () -> Unit
) {
    val context = LocalContext.current
    val coroutineScope = rememberCoroutineScope()
    val credentialManager = remember { CredentialManager.create(context) }
    var isLoading by remember { mutableStateOf(false) }
    var errorMessage by remember { mutableStateOf<String?>(null) }

    val gradientBrush = remember {
        Brush.linearGradient(
            colors = listOf(PrismPurple, PrismPink, PrismOrange)
        )
    }

    Surface(
        modifier = Modifier.fillMaxSize(),
        color = MaterialTheme.colorScheme.background
    ) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(horizontal = 28.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.Center
        ) {
            // App Branding Logo with Neon Prism Ring
            ShdMediaLogoBadge(
                size = 104.dp,
                cornerRadius = 26.dp
            )

            Spacer(modifier = Modifier.height(20.dp))

            Text(
                text = "SHD Media",
                style = MaterialTheme.typography.displayLarge,
                color = MaterialTheme.colorScheme.onBackground
            )

            Text(
                text = "Share Moments & Videos with the World",
                style = MaterialTheme.typography.bodyLarge,
                color = MaterialTheme.colorScheme.onSurfaceVariant
            )

            Spacer(modifier = Modifier.height(32.dp))

            // Value props
            Card(
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.6f)),
                shape = RoundedCornerShape(20.dp),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(18.dp)) {
                    FeaturePill(icon = Icons.Default.CameraAlt, title = "Visual Storytelling", desc = "Share high-res photos with creative filters")
                    Spacer(modifier = Modifier.height(14.dp))
                    FeaturePill(icon = Icons.Default.ChatBubble, title = "Direct Messaging", desc = "Instant real-time 1-on-1 private messaging")
                    Spacer(modifier = Modifier.height(14.dp))
                    FeaturePill(icon = Icons.Default.Notifications, title = "Live Notifications", desc = "Instant alerts for likes, comments & follows")
                    Spacer(modifier = Modifier.height(14.dp))
                    FeaturePill(icon = Icons.Default.AutoAwesome, title = "Gemini Creative AI", desc = "Intelligent captions, vibe tags & smart replies")
                }
            }

            Spacer(modifier = Modifier.height(36.dp))

            // Google Sign-In interactive button
            Button(
                onClick = {
                    isLoading = true
                    errorMessage = null
                    onGoogleSignInClicked(
                        context = context,
                        credentialManager = credentialManager,
                        onAuthSuccess = {
                            isLoading = false
                            onAuthSuccess()
                        },
                        onAuthError = { err ->
                            isLoading = false
                            errorMessage = err
                        },
                        scope = coroutineScope,
                        onAuthCancelled = {
                            isLoading = false
                        }
                    )
                },
                enabled = !isLoading,
                shape = RoundedCornerShape(16.dp),
                colors = ButtonDefaults.buttonColors(containerColor = Color.Transparent),
                modifier = Modifier
                    .fillMaxWidth()
                    .height(54.dp)
                    .background(gradientBrush, shape = RoundedCornerShape(16.dp))
                    .testTag("google_sign_in_button")
            ) {
                if (isLoading) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(24.dp),
                        color = Color.White,
                        strokeWidth = 2.dp
                    )
                } else {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Text(
                            text = "G  Sign in with Google",
                            style = MaterialTheme.typography.titleMedium,
                            fontWeight = FontWeight.Bold,
                            color = Color.White
                        )
                    }
                }
            }

            AnimatedVisibility(visible = errorMessage != null) {
                errorMessage?.let { msg ->
                    Text(
                        text = msg,
                        color = MaterialTheme.colorScheme.error,
                        style = MaterialTheme.typography.bodyMedium,
                        textAlign = TextAlign.Center,
                        modifier = Modifier.padding(top = 16.dp)
                    )
                }
            }
        }
    }
}

